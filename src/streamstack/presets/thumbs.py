"""Look thumbnails: a synthetic test portrait with a look applied, written as a small PNG.

The scene is generated by `sample_scene` (no photograph, so no licence question): a backdrop with a window and a
plant, a person with skin, hair and a dark shirt, and a strip of colour patches and a grey ramp underneath, so a look's
effect on skin, neutrals, saturated colour, shadows and highlights is visible at once.

`grade` is the Python twin of the Console's `look-swatch.js` (brightness adds, contrast scales around mid grey,
gamma bends the mid-tones, saturation scales colour distance from luma, warmth pushes red up and blue down) and then
applies the look's real 3D LUT, when it has one, with trilinear sampling at the look's `lut_amount`.
"""

from __future__ import annotations

import math
import struct
import zlib
from collections.abc import Mapping
from pathlib import Path

from streamstack.presets.luts import Lut3D, Rgb, clamp

WIDTH, HEIGHT = 128, 80

SKIN: Rgb = (0.86, 0.62, 0.50)


def _mix(a: Rgb, b: Rgb, t: float) -> Rgb:
    t = clamp(t)
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t)


def _shade(color: Rgb, factor: float) -> Rgb:
    return (clamp(color[0] * factor), clamp(color[1] * factor), clamp(color[2] * factor))


PATCHES: tuple[Rgb, ...] = (
    (0.86, 0.62, 0.50),
    (0.95, 0.85, 0.12),
    (0.12, 0.80, 0.85),
    (0.15, 0.72, 0.25),
    (0.85, 0.20, 0.75),
    (0.88, 0.16, 0.14),
    (0.18, 0.28, 0.88),
)


def sample_scene(width: int = WIDTH, height: int = HEIGHT) -> list[list[Rgb]]:
    """Rows of linear-ish sRGB triples in 0..1."""
    rows: list[list[Rgb]] = []
    chart_top = int(height * 0.86)
    for y in range(height):
        row: list[Rgb] = []
        v = y / (height - 1)
        for x in range(width):
            u = x / (width - 1)
            if y >= chart_top:
                if u < 0.58:
                    t = u / 0.58
                    row.append((t, t, t))
                else:
                    index = min(len(PATCHES) - 1, int((u - 0.58) / 0.42 * len(PATCHES)))
                    row.append(PATCHES[index])
                continue
            # backdrop: a cool wall that warms toward the floor
            pixel = _mix((0.40, 0.47, 0.55), (0.56, 0.50, 0.44), v / 0.86)
            # a bright window with a soft blown edge
            if 0.74 <= u <= 0.96 and 0.08 <= v <= 0.52:
                edge = min(u - 0.74, 0.96 - u, v - 0.08, 0.52 - v)
                pixel = _mix(pixel, (0.97, 0.98, 1.0), edge / 0.025)
            # a plant
            plant = math.hypot((u - 0.10) * 1.6, v - 0.50)
            if plant < 0.17:
                pixel = _mix(pixel, _shade((0.20, 0.52, 0.24), 1.15 - plant * 3), (0.17 - plant) / 0.02)
            # shoulders and shirt
            body = ((u - 0.45) / 0.34) ** 2 + ((v - 0.98) / 0.34) ** 2
            if body < 1.0:
                pixel = _mix(pixel, _shade((0.16, 0.22, 0.42), 1.2 - 0.5 * body), (1.0 - body) / 0.06)
            # neck
            if abs(u - 0.45) < 0.055 and 0.55 < v < 0.74:
                pixel = _shade(SKIN, 0.78)
            # head, lit from the window side
            head = ((u - 0.45) / 0.14) ** 2 + ((v - 0.36) / 0.23) ** 2
            if head < 1.0:
                side = 1.1 + 0.25 * (u - 0.45) / 0.14 - 0.25 * (v - 0.36) / 0.23
                pixel = _mix(pixel, _shade(SKIN, clamp(side) + 0.12), (1.0 - head) / 0.07)
                hair = ((u - 0.45) / 0.15) ** 2 + ((v - 0.25) / 0.14) ** 2
                if hair < 1.0 and v < 0.30:
                    pixel = _mix(pixel, (0.16, 0.11, 0.08), (1.0 - hair) / 0.1)
                for eye in (0.405, 0.495):
                    if math.hypot((u - eye) * 1.7, v - 0.36) < 0.022:
                        pixel = (0.12, 0.08, 0.06)
                if abs(u - 0.45) < 0.04 and abs(v - 0.50) < 0.012:
                    pixel = _shade((0.72, 0.30, 0.30), 1.0)
            row.append(pixel)
        rows.append(row)
    return rows


def grade(rgb: Rgb, values: Mapping[str, float | bool], lut: Lut3D | None = None) -> Rgb:
    """Apply a look (the engine's nine parameters, plus the look's 3D LUT) to one pixel."""
    bright = float(values.get("brightness", 0.0))
    contrast = float(values.get("contrast", 0.0))
    gamma = float(values.get("gamma", 0.0))
    sat = float(values.get("saturation", 0.0))
    warm = float(values.get("warmth", 0.0))
    amount = float(values.get("lut_amount", 0.0)) if values.get("lut_enabled") else 0.0

    c = [clamp(x) ** (1.0 / (1.0 + gamma * 0.9)) for x in rgb]
    c = [x + bright for x in c]
    c = [(x - 0.5) * (1.0 + contrast * 1.1) + 0.5 for x in c]
    y = 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
    c = [y + (x - y) * (1.0 + sat) for x in c]
    c[0] += warm * 0.09
    c[2] -= warm * 0.11
    out: Rgb = (clamp(c[0]), clamp(c[1]), clamp(c[2]))
    if lut is not None and amount > 0.0:
        mapped = lut.sample(out)
        out = (
            out[0] + (mapped[0] - out[0]) * amount,
            out[1] + (mapped[1] - out[1]) * amount,
            out[2] + (mapped[2] - out[2]) * amount,
        )
    return (clamp(out[0]), clamp(out[1]), clamp(out[2]))


def render(values: Mapping[str, float | bool], lut: Lut3D | None = None) -> bytes:
    """RGB bytes (WIDTH x HEIGHT x 3) of the test scene with the look applied."""
    scene = sample_scene()
    out = bytearray()
    for row in scene:
        for pixel in row:
            r, g, b = grade(pixel, values, lut)
            out += bytes((round(r * 255), round(g * 255), round(b * 255)))
    return bytes(out)


def png(rgb: bytes, width: int = WIDTH, height: int = HEIGHT) -> bytes:
    """An 8-bit RGB PNG (Sub-filtered, level 9) from raw RGB bytes."""
    if len(rgb) != width * height * 3:
        raise ValueError("pixel data does not match the image size")
    stride = width * 3
    raw = bytearray()
    for y in range(height):
        line = rgb[y * stride : (y + 1) * stride]
        raw.append(1)  # filter type Sub: each byte minus the one a pixel to the left
        raw += bytes((line[i] - (line[i - 3] if i >= 3 else 0)) & 0xFF for i in range(stride))

    def chunk(kind: bytes, data: bytes) -> bytes:
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + chunk(b"IEND", b"")
    )


def decode_png(data: bytes) -> tuple[int, int, bytes]:
    """Read back a PNG written by `png` (8-bit RGB, filter types None and Sub). Used by the tests."""
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG")
    pos, width, height, idat = 8, 0, 0, b""
    while pos < len(data):
        (length,) = struct.unpack(">I", data[pos : pos + 4])
        kind, body = data[pos + 4 : pos + 8], data[pos + 8 : pos + 8 + length]
        if kind == b"IHDR":
            width, height, depth, color = struct.unpack(">IIBB", body[:10])
            if (depth, color) != (8, 2):
                raise ValueError("only 8-bit RGB is supported")
        elif kind == b"IDAT":
            idat += body
        pos += 12 + length
    raw = zlib.decompress(idat)
    stride, out = width * 3, bytearray()
    for y in range(height):
        kind, line = raw[y * (stride + 1)], raw[y * (stride + 1) + 1 : (y + 1) * (stride + 1)]
        if kind not in (0, 1):
            raise ValueError(f"unsupported PNG filter {kind}")
        row = bytearray(line)
        if kind == 1:
            for i in range(3, stride):
                row[i] = (row[i] + row[i - 3]) & 0xFF
        out += row
    return width, height, bytes(out)


def slug(name: str) -> str:
    """A look's file name: lower case letters and digits joined by hyphens."""
    out, last = [], "-"
    for ch in name.lower():
        keep = ch if ch.isascii() and ch.isalnum() else "-"
        if keep == "-" and last == "-":
            continue
        out.append(keep)
        last = keep
    return "".join(out).strip("-")


def write_thumb(path: Path, values: Mapping[str, float | bool], lut: Lut3D | None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png(render(values, lut)))
