"""The GPU shaders the engine hooks into libplacebo, generated from templates.

libplacebo's ffmpeg filter takes a custom shader at init only (`custom_shader_path`; no option that a shader could
read is settable at run time), so a shader's strength is a constant in its source and each strength is its own
file. `ensure_sharpen` writes the file for one strength; `graph.sharpen_shader_path` says where it will be, so the
graph text stays a pure function. Files are written once, atomically, and never changed afterwards.

The sharpen shader is AMD's contrast-adaptive sharpening (FidelityFX CAS, MIT), the published algorithm, written out
for the mpv `.hook` format libplacebo reads and run on the picture in the colour the output is encoded from. Its
strength constant is CAS's `sharpness` (0 to 1), the number the sharpen slider already is. On grey test pictures it
matches a numpy implementation of the algorithm to a mean of 0.1 to 0.3 grey levels (tests/test_engine_shaders.py runs
that comparison on the GPU where there is one). It does not reproduce ffmpeg's CPU `cas` filter level for level: the
CPU filter's response is not monotonic in its strength (measured, docs/native-video-engine.md), the shader's is.
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path

from streamstack.engine.graph import sharpen_shader_path

SHARPEN_TEMPLATE = """\
//!HOOK OUTPUT
//!BIND HOOKED
//!DESC streamstack contrast adaptive sharpen (strength @STRENGTH@)

// Generated by streamstack.engine.shaders; the strength is a constant because libplacebo cannot change a shader
// parameter while the filter runs. Contrast adaptive sharpening after AMD FidelityFX CAS (MIT).
#define SHARPNESS @STRENGTH@

vec4 hook() {
    vec4 centre = HOOKED_tex(HOOKED_pos);
    vec3 e = centre.rgb;
    vec3 b = HOOKED_texOff(vec2( 0.0, -1.0)).rgb;
    vec3 d = HOOKED_texOff(vec2(-1.0,  0.0)).rgb;
    vec3 f = HOOKED_texOff(vec2( 1.0,  0.0)).rgb;
    vec3 h = HOOKED_texOff(vec2( 0.0,  1.0)).rgb;

    vec3 lo = min(min(min(d, e), min(f, b)), h);
    vec3 hi = max(max(max(d, e), max(f, b)), h);
    // how much room the neighbourhood leaves to the sharpening before it would clip (per channel)
    vec3 amp = sqrt(clamp(min(lo, 1.0 - hi) / max(hi, vec3(1e-4)), 0.0, 1.0));
    vec3 w = amp * (-1.0 / mix(8.0, 5.0, SHARPNESS));

    vec3 sharp = ((b + d + f + h) * w + e) / (4.0 * w + 1.0);
    return vec4(clamp(sharp, 0.0, 1.0), centre.a);
}
"""


def sharpen_source(level: float) -> str:
    """The GLSL hook for a CAS strength between 0 and 1."""
    if not 0.0 < level <= 1.0:
        raise ValueError(f"a sharpen strength is above 0 and at most 1, not {level}")
    return SHARPEN_TEMPLATE.replace("@STRENGTH@", f"{level:.2f}")


def ensure_sharpen(directory: str | Path, level: float) -> str:
    """Make sure the shader for `level` exists under `directory`; returns its path.

    Raises OSError when the directory cannot be made or written (the supervisor then runs without the sharpen
    stage and says so).
    """
    path = Path(sharpen_shader_path(str(directory), level))
    text = sharpen_source(level)
    try:
        if path.read_text() == text:
            return str(path)
    except FileNotFoundError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".cas-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w") as handle:
            handle.write(text)
        os.replace(tmp, path)
    except OSError:
        try:
            os.unlink(tmp)
        except FileNotFoundError:
            pass
        raise
    return str(path)
