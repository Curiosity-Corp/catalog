"""Procedural 3D colour LUTs (.cube) for the cinematography looks.

Every LUT here is *generated by this file*: a handful of tone and colour operations (lift, gamma, gain, saturation,
split-toning, an S-curve) applied to an identity cube. No film scan, no third-party LUT and no vendor profile is
involved, so the generated ``.cube`` files carry no licence encumbrance. They are released under the same
Apache-2.0 licence as StreamStack (CC0 for anyone who prefers it).

The files are shipped in ``data/presets/luts/`` and rebuilt with ``python -m streamstack.presets.build``; a test
checks that the shipped files match this generator byte for byte.

``.cube`` format (Adobe/Resolve): ``LUT_3D_SIZE N``, then N^3 lines of ``r g b`` with red changing fastest.
"""

from __future__ import annotations

import math
from collections.abc import Callable
from pathlib import Path

Rgb = tuple[float, float, float]
SIZE = 17  # 17^3 = 4913 entries: smooth for gentle grades, about 100 kB per file

LICENCE = "Generated procedurally by streamstack.presets.luts. Apache-2.0 (CC0 for anyone who prefers it)."


def clamp(value: float) -> float:
    return 0.0 if value < 0.0 else 1.0 if value > 1.0 else value


def luma(rgb: Rgb) -> float:
    return 0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2]


def saturate(rgb: Rgb, amount: float) -> Rgb:
    """amount 1 keeps the colour, 0 is grey, above 1 pushes it."""
    y = luma(rgb)
    return (y + (rgb[0] - y) * amount, y + (rgb[1] - y) * amount, y + (rgb[2] - y) * amount)


def s_curve(value: float, strength: float) -> float:
    """A smooth contrast curve around mid grey; strength 0 is the identity."""
    value = clamp(value)
    shaped = value * value * (3.0 - 2.0 * value)
    return value + (shaped - value) * strength


def lift_gamma_gain(rgb: Rgb, lift: Rgb = (0, 0, 0), gamma: float = 1.0, gain: Rgb = (1, 1, 1)) -> Rgb:
    out = []
    for channel, low, mul in zip(rgb, lift, gain, strict=True):
        value = clamp(channel) * mul
        value = low + value * (1.0 - low)
        out.append(clamp(value) ** (1.0 / gamma))
    return (out[0], out[1], out[2])


def split_tone(rgb: Rgb, shadows: Rgb, highlights: Rgb, amount: float) -> Rgb:
    """Push shadows toward one colour and highlights toward another. Tints are small signed offsets."""
    y = clamp(luma(rgb))
    shadow_weight = (1.0 - y) ** 2
    high_weight = y**2
    r, g, b = (rgb[i] + amount * (shadows[i] * shadow_weight + highlights[i] * high_weight) for i in range(3))
    return (r, g, b)


def mono(rgb: Rgb, red: float = 0.30, green: float = 0.59, blue: float = 0.11) -> Rgb:
    """A black-and-white conversion with a channel mix (a red filter darkens skies, and so on)."""
    y = red * rgb[0] + green * rgb[1] + blue * rgb[2]
    return (y, y, y)


def _tail(rgb: Rgb) -> Rgb:
    return (clamp(rgb[0]), clamp(rgb[1]), clamp(rgb[2]))


def _curve(rgb: Rgb, strength: float) -> Rgb:
    return (s_curve(rgb[0], strength), s_curve(rgb[1], strength), s_curve(rgb[2], strength))


def teal_orange(rgb: Rgb) -> Rgb:
    out = split_tone(rgb, (-0.07, 0.02, 0.09), (0.09, 0.025, -0.08), 1.0)
    out = saturate(out, 1.05)
    return _curve(out, 0.35)


def portra(rgb: Rgb) -> Rgb:
    out = lift_gamma_gain(rgb, lift=(0.03, 0.025, 0.02), gamma=1.08, gain=(1.0, 0.985, 0.95))
    out = saturate(out, 0.92)
    out = split_tone(out, (0.005, 0.01, 0.0), (0.03, 0.012, -0.02), 1.0)
    return _curve(out, 0.12)


def velvia(rgb: Rgb) -> Rgb:
    out = saturate(rgb, 1.45)
    out = _curve(out, 0.5)
    out = (out[0] * 1.02, out[1], out[2] * 1.02)
    return _tail(out)


def cinestill(rgb: Rgb) -> Rgb:
    out = split_tone(rgb, (-0.04, 0.03, 0.08), (0.08, -0.005, -0.04), 1.0)
    y = clamp(luma(rgb))
    glow = max(0.0, y - 0.72) / 0.28  # the red halation bleeding out of bright areas
    out = (out[0] + 0.12 * glow, out[1] + 0.02 * glow, out[2])
    out = saturate(out, 1.05)
    return _curve(out, 0.3)


def classic_chrome(rgb: Rgb) -> Rgb:
    out = saturate(rgb, 0.78)
    out = split_tone(out, (-0.015, 0.0, 0.03), (0.02, 0.012, -0.02), 1.0)
    out = lift_gamma_gain(_tail(out), lift=(0.012, 0.012, 0.014), gamma=0.97)
    return _curve(out, 0.4)


def vintage_fade(rgb: Rgb) -> Rgb:
    out = lift_gamma_gain(rgb, lift=(0.09, 0.08, 0.095), gamma=1.06, gain=(1.0, 0.97, 0.9))
    out = saturate(out, 0.8)
    out = split_tone(out, (-0.01, 0.03, 0.025), (0.05, 0.02, -0.04), 1.0)
    return _tail(out)


def bleach_bypass(rgb: Rgb) -> Rgb:
    y = luma(rgb)
    grey = (y, y, y)
    # an overlay blend of the colour onto its own luma, the lab trick this look is named for
    ov = [2 * g * c if g < 0.5 else 1 - 2 * (1 - g) * (1 - c) for g, c in zip(grey, rgb, strict=True)]
    mixed = (rgb[0] * 0.4 + ov[0] * 0.6, rgb[1] * 0.4 + ov[1] * 0.6, rgb[2] * 0.4 + ov[2] * 0.6)
    return _tail(saturate(_tail(mixed), 0.7))


def cross_process(rgb: Rgb) -> Rgb:
    r, g, b = (clamp(c) for c in rgb)
    out = (
        s_curve(r, 0.8) * 1.04,  # red climbs steeply
        g + 0.05 * math.sin(g * math.pi),  # green lifts in the mids
        0.12 + b * 0.78,  # blue is lifted in the shadows and capped in the highlights
    )
    return _tail(saturate(_tail(out), 1.15))


def cold_steel(rgb: Rgb) -> Rgb:
    out = split_tone(rgb, (-0.05, 0.0, 0.08), (-0.02, 0.01, 0.05), 1.0)
    out = saturate(out, 0.85)
    return _curve(out, 0.4)


def golden_hour(rgb: Rgb) -> Rgb:
    out = lift_gamma_gain(rgb, gamma=1.04, gain=(1.05, 1.0, 0.86))
    out = split_tone(out, (0.02, 0.0, -0.015), (0.07, 0.035, -0.06), 1.0)
    out = saturate(out, 1.1)
    return _curve(out, 0.18)


def neon_split(rgb: Rgb) -> Rgb:
    out = split_tone(rgb, (-0.04, 0.02, 0.1), (0.1, -0.03, 0.05), 1.0)  # cyan-blue shadows, magenta highlights
    out = saturate(out, 1.25)
    return _curve(out, 0.45)


def noir(rgb: Rgb) -> Rgb:
    y = mono(_tail(rgb), 0.40, 0.50, 0.10)[0]  # a red-leaning mix: skin glows, shadows go deep
    y = s_curve(y, 0.7)
    y = y**1.08
    return (y, y, y)


LUTS: dict[str, tuple[str, Callable[[Rgb], Rgb]]] = {
    "teal-orange": ("Teal and orange split-tone", teal_orange),
    "portra": ("Soft warm portrait negative", portra),
    "velvia": ("Saturated slide film", velvia),
    "cinestill": ("Tungsten cinema stock with red halation", cinestill),
    "classic-chrome": ("Muted documentary slide", classic_chrome),
    "vintage-fade": ("Faded amber print", vintage_fade),
    "bleach-bypass": ("Silvery bleach bypass", bleach_bypass),
    "cross-process": ("Cross-processed slide", cross_process),
    "cold-steel": ("Cold metallic grade", cold_steel),
    "golden-hour": ("Low-sun warm glow", golden_hour),
    "neon-split": ("Cyan and magenta neon split", neon_split),
    "noir": ("Contrasty red-filter black and white", noir),
}


def build_cube(name: str, size: int = SIZE) -> str:
    """The text of one .cube file."""
    title, transform = LUTS[name]
    lines = [
        f'TITLE "StreamStack {title}"',
        f"# {LICENCE}",
        f"LUT_3D_SIZE {size}",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
    ]
    last = size - 1
    for b in range(size):
        for g in range(size):
            for r in range(size):
                out = transform((r / last, g / last, b / last))
                lines.append(f"{clamp(out[0]):.5f} {clamp(out[1]):.5f} {clamp(out[2]):.5f}")
    return "\n".join(lines) + "\n"


class Lut3D:
    """A parsed .cube with trilinear sampling (used to render the look thumbnails)."""

    def __init__(self, size: int, table: list[Rgb]) -> None:
        if size < 2 or len(table) != size**3:
            raise ValueError(f"a {size}-point 3D LUT needs {size**3} entries, got {len(table)}")
        self.size, self.table = size, table

    @classmethod
    def parse(cls, text: str) -> Lut3D:
        size = 0
        table: list[Rgb] = []
        for raw in text.splitlines():
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            key = line.split()[0]
            if key == "LUT_3D_SIZE":
                size = int(line.split()[1])
            elif key in ("TITLE", "DOMAIN_MIN", "DOMAIN_MAX", "LUT_1D_SIZE"):
                if key == "LUT_1D_SIZE":
                    raise ValueError("1D LUTs are not supported")
            else:
                r, g, b = (float(v) for v in line.split())
                table.append((r, g, b))
        return cls(size, table)

    @classmethod
    def load(cls, path: Path) -> Lut3D:
        return cls.parse(path.read_text(encoding="utf-8"))

    def sample(self, rgb: Rgb) -> Rgb:
        n = self.size - 1
        pos = [clamp(c) * n for c in rgb]
        base = [min(int(p), n - 1) for p in pos]
        frac = [p - b for p, b in zip(pos, base, strict=True)]
        out = [0.0, 0.0, 0.0]
        for corner in range(8):
            dr, dg, db = corner & 1, (corner >> 1) & 1, (corner >> 2) & 1
            weight = (
                (frac[0] if dr else 1 - frac[0]) * (frac[1] if dg else 1 - frac[1]) * (frac[2] if db else 1 - frac[2])
            )
            if weight == 0.0:
                continue
            index = (base[2] + db) * self.size * self.size + (base[1] + dg) * self.size + base[0] + dr
            entry = self.table[index]
            out[0] += weight * entry[0]
            out[1] += weight * entry[1]
            out[2] += weight * entry[2]
        return (out[0], out[1], out[2])
