#!/usr/bin/env python3
"""Check a built collection artifact against THIRD_PARTY_INVENTORY.yml.

The source checkout is not what users receive: `ansible-galaxy collection build`
applies `build_ignore`, so only the tarball shows what is actually redistributed.
This script scans that tarball and fails when

* the inventory is malformed, or a path pattern of a shipped entry matches nothing
  in the artifact (stale entry);
* a file the inventory lists as excluded (ambiguous provenance) is in the artifact;
* an entry whose provenance is `unresolved` is in the artifact;
* an artifact file looks third-party (licence or copyright header, fonts, installers,
  archives, binaries, images, key material) and no inventory entry covers it;
* NOTICE lacks the text an entry requires, or the licence text file is missing;
* a pinned version recorded in the inventory differs from the one in the artifact;
* the artifact's copy of the inventory differs from the one that was checked.

Usage:
    python scripts/check_third_party_inventory.py --build            # build to a temp dir, scan
    python scripts/check_third_party_inventory.py ARTIFACT.tar.gz    # scan an existing tarball
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
INVENTORY = "THIRD_PARTY_INVENTORY.yml"

KINDS = {"vendored", "derived", "first-party", "runtime", "key-material", "patch"}
STATUSES = {"shipped", "excluded", "runtime"}
PROVENANCE = {"resolved", "needs-review", "unresolved"}
REQUIRED_FIELDS = (
    "id",
    "name",
    "kind",
    "status",
    "provenance",
    "paths",
    "source",
    "version",
    "license",
    "redistribution",
)
# Files every artifact must carry so the notices travel with the code.
REQUIRED_IN_ARTIFACT = ("LICENSE", "NOTICE", "THIRD_PARTY.md", INVENTORY)
# Generated by ansible-galaxy; not collection content.
GENERATED = {"MANIFEST.json", "FILES.json"}

BINARY_SUFFIXES = {
    ".ttf", ".otf", ".woff", ".woff2", ".eot",  # fonts
    ".deb", ".rpm", ".run", ".appimage", ".exe", ".msi", ".pkg", ".dmg",  # installers
    ".so", ".dll", ".dylib", ".a", ".o", ".ko", ".whl", ".jar", ".onnx", ".pt", ".pth", ".bin",
    ".zip", ".tar", ".tgz", ".gz", ".xz", ".bz2", ".zst", ".7z", ".iso",  # archives
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".avif", ".bmp", ".tif", ".tiff", ".ico", ".icns", ".svg",
    ".mp3", ".wav", ".ogg", ".flac", ".mp4", ".webm", ".mkv", ".pdf",
}

HEADER_LINES = 40
HEADER_MARKERS = (
    re.compile(r"SPDX-License-Identifier", re.I),
    re.compile(r"\bcopyright\b\s*(?:\(c\)|©|\d{4})", re.I),
    re.compile(r"\b(?:released|licensed|distributed)\s+under\b", re.I),
    re.compile(r"^\W*licen[cs]e\s*:\s*\S", re.I),
    re.compile(r"GNU\s+(?:Lesser\s+|Affero\s+)?General\s+Public", re.I),
    re.compile(r"Permission is hereby granted", re.I),
    re.compile(r"\b(?:based on|forked from|ported from|adapted from|derived from)\b[^\n]*\bby\b", re.I),
)
WHOLE_FILE_MARKERS = (
    re.compile(r"\bSCRIPT_LICENSE\s*=", re.I),
    re.compile(r"^\s*-----BEGIN (?:PGP PUBLIC KEY BLOCK|CERTIFICATE|PUBLIC KEY)-----\s*$", re.M),
)
MAX_SCAN_BYTES = 2_000_000


def glob_regex(pattern: str) -> re.Pattern[str]:
    """`**` crosses directories, `*` and `?` do not; a trailing `/` means the whole tree."""
    if pattern.endswith("/"):
        pattern += "**"
    out, i = [], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("".join(out) + r"\Z")


def normalise(text: str) -> str:
    return " ".join(text.split())


def read_artifact(path: Path) -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    with tarfile.open(path, "r:*") as archive:
        for member in archive.getmembers():
            if not member.isfile():
                continue
            name = member.name[2:] if member.name.startswith("./") else member.name
            handle = archive.extractfile(member)
            assert handle is not None
            files[name] = handle.read()
    return files


def looks_third_party(name: str, data: bytes) -> str | None:
    """Return why a file needs an inventory entry, or None."""
    suffix = Path(name).suffix.lower()
    if suffix in BINARY_SUFFIXES:
        return f"{suffix} asset/binary"
    if b"\0" in data[:4096] or len(data) > MAX_SCAN_BYTES:
        return "binary or oversized file"
    text = data.decode("utf-8", errors="replace")
    header = "\n".join(text.splitlines()[:HEADER_LINES])
    for marker in HEADER_MARKERS:
        if marker.search(header):
            return f"header matches /{marker.pattern}/"
    for marker in WHOLE_FILE_MARKERS:
        if marker.search(text):
            return f"content matches /{marker.pattern}/"
    return None


def validate_schema(inventory: object) -> tuple[list[dict], list[str]]:
    errors: list[str] = []
    if not isinstance(inventory, dict) or not isinstance(inventory.get("entries"), list):
        return [], [f"{INVENTORY}: top level must be a mapping with an `entries` list"]
    first_party = inventory.get("first_party_paths", [])
    if not isinstance(first_party, list) or not all(isinstance(p, str) for p in first_party):
        errors.append(f"{INVENTORY}: `first_party_paths` must be a list of strings")
    entries: list[dict] = []
    seen: set[str] = set()
    for index, entry in enumerate(inventory["entries"]):
        label = entry.get("id", f"#{index}") if isinstance(entry, dict) else f"#{index}"
        if not isinstance(entry, dict):
            errors.append(f"entry {label}: must be a mapping")
            continue
        missing = [f for f in REQUIRED_FIELDS if entry.get(f) in (None, "", [])]
        # runtime entries are not in the artifact, so they have no paths to list
        missing = [f for f in missing if not (f == "paths" and entry.get("status") == "runtime")]
        if missing:
            errors.append(f"entry {label}: missing {', '.join(missing)}")
        if entry.get("id") in seen:
            errors.append(f"entry {label}: duplicate id")
        seen.add(str(entry.get("id")))
        if entry.get("kind") not in KINDS:
            errors.append(f"entry {label}: kind must be one of {sorted(KINDS)}")
        if entry.get("status") not in STATUSES:
            errors.append(f"entry {label}: status must be one of {sorted(STATUSES)}")
        if entry.get("provenance") not in PROVENANCE:
            errors.append(f"entry {label}: provenance must be one of {sorted(PROVENANCE)}")
        for field in ("paths", "except"):
            value = entry.get(field) or []
            if not isinstance(value, list) or not all(isinstance(p, str) for p in value):
                errors.append(f"entry {label}: {field} must be a list of strings")
        paths = entry.get("paths") or []
        if entry.get("status") == "runtime" and paths:
            errors.append(f"entry {label}: runtime entries are fetched at run time and must not list paths")
        if entry.get("status") == "excluded" and entry.get("provenance") == "resolved":
            errors.append(f"entry {label}: only unresolved or needs-review material is excluded")
        if entry.get("notice") and not entry.get("notice_text"):
            errors.append(f"entry {label}: notice: true needs notice_text")
        entries.append(entry)
    return entries, errors


def check(artifact: dict[str, bytes], inventory: dict, inventory_bytes: bytes) -> tuple[list[str], list[str]]:
    """Return (errors, notes)."""
    entries, errors = validate_schema(inventory)
    notes: list[str] = []
    names = sorted(n for n in artifact if n not in GENERATED)

    for required in REQUIRED_IN_ARTIFACT:
        if required not in artifact:
            errors.append(f"artifact is missing {required}")
    if INVENTORY in artifact and artifact[INVENTORY] != inventory_bytes:
        errors.append(f"artifact copy of {INVENTORY} differs from the inventory that was checked")

    covered: dict[str, list[str]] = {}
    for entry in entries:
        label = entry.get("id", "?")
        status, provenance = entry.get("status"), entry.get("provenance")
        patterns = [glob_regex(p) for p in entry.get("paths") or []]
        except_patterns = [glob_regex(p) for p in entry.get("except") or []]
        matched = sorted(
            n for n in names if any(p.match(n) for p in patterns) and not any(p.match(n) for p in except_patterns)
        )
        for n in matched:
            covered.setdefault(n, []).append(label)
        if status == "shipped":
            for raw, pattern in zip(entry.get("paths") or [], patterns):
                if not any(pattern.match(n) and n in matched for n in names):
                    errors.append(f"entry {label}: path `{raw}` matches nothing in the artifact (stale entry?)")
            if provenance == "unresolved":
                errors.append(f"entry {label}: provenance is unresolved but {len(matched)} file(s) are in the artifact; exclude them")
            if provenance == "needs-review":
                notes.append(f"needs-review (shipped): {label}")
            if entry.get("notice"):
                text = normalise(artifact.get("NOTICE", b"").decode("utf-8", errors="replace"))
                for snippet in entry.get("notice_text") or []:
                    if normalise(snippet) not in text:
                        errors.append(f"entry {label}: NOTICE does not contain: {snippet!r}")
                license_file = entry.get("license_file")
                if license_file and not artifact.get(license_file, b"").strip():
                    errors.append(f"entry {label}: licence text {license_file} is missing or empty in the artifact")
        elif status == "excluded":
            for n in matched:
                errors.append(f"entry {label}: excluded file is in the artifact: {n}")
            notes.append(f"excluded: {label} ({provenance})")
        for pin in entry.get("pins") or []:
            errors.extend(check_pin(label, entry, pin, artifact))

    first_party = [glob_regex(p) for p in inventory.get("first_party_paths", [])]
    for name in names:
        if name in covered or any(p.match(name) for p in first_party):
            continue
        reason = looks_third_party(name, artifact[name])
        if reason:
            errors.append(f"uninventoried third-party-looking file in the artifact: {name} ({reason})")
    return errors, notes


def check_pin(label: str, entry: dict, pin: dict, artifact: dict[str, bytes]) -> list[str]:
    path = pin.get("file", "")
    if path not in artifact:
        return [f"entry {label}: pinned file {path} is not in the artifact"]
    text = artifact[path].decode("utf-8", errors="replace")
    expected = str(entry.get("version"))
    if "key" in pin:
        document = yaml.safe_load(text) or {}
        found = document.get(pin["key"]) if isinstance(document, dict) else None
        if found is None:
            return [f"entry {label}: {path} has no key {pin['key']}"]
        value = str(found)
    elif "regex" in pin:
        match = re.search(pin["regex"], text, re.M)
        if not match:
            return [f"entry {label}: {path} does not match /{pin['regex']}/"]
        value = match.group(1)
    else:
        return [f"entry {label}: a pin needs `key` or `regex`"]
    if value != expected:
        return [f"entry {label}: inventory records version {expected!r} but {path} pins {value!r}; update the inventory"]
    return []


def build_artifact(root: Path, out_dir: Path) -> Path:
    if shutil.which("ansible-galaxy") is None:
        raise SystemExit("ansible-galaxy is required to build the collection")
    result = subprocess.run(
        ["ansible-galaxy", "collection", "build", "--force", "--output-path", str(out_dir), str(root)],
        capture_output=True,
        text=True,
        check=False,
    )
    tarballs = sorted(out_dir.glob("*.tar.gz"))
    if result.returncode != 0 or len(tarballs) != 1:
        raise SystemExit(f"collection build failed (exit {result.returncode}):\n{result.stdout}\n{result.stderr}")
    return tarballs[0]


def run(artifact_path: Path, inventory_path: Path) -> int:
    inventory_bytes = inventory_path.read_bytes()
    inventory = yaml.safe_load(inventory_bytes)
    artifact = read_artifact(artifact_path)
    errors, notes = check(artifact, inventory, inventory_bytes)
    entries = inventory.get("entries", []) if isinstance(inventory, dict) else []
    print(f"artifact: {artifact_path.name} ({len(artifact)} files); inventory entries: {len(entries)}")
    for note in notes:
        print(f"  note: {note}")
    for error in errors:
        print(f"  ERROR: {error}")
    print("third-party inventory: " + ("FAILED" if errors else "OK"))
    return 1 if errors else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("artifact", nargs="?", type=Path, help="built collection tarball")
    parser.add_argument("--build", action="store_true", help="build the collection into a temp dir and scan that")
    parser.add_argument("--inventory", type=Path, default=ROOT / INVENTORY)
    args = parser.parse_args()
    if bool(args.artifact) == args.build:
        parser.error("give either ARTIFACT or --build")
    if args.build:
        with tempfile.TemporaryDirectory(prefix="collection-licenses-") as tmp:
            return run(build_artifact(ROOT, Path(tmp)), args.inventory)
    return run(args.artifact, args.inventory)


if __name__ == "__main__":
    sys.exit(main())
